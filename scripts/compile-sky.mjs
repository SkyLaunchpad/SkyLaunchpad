import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import solc from "solc";

const root = "/workspace";
const files = ["SkyParams.sol", "SkyToken.sol", "SkyCurve.sol", "SkyHook.sol", "SkyPool.sol", "SkyRewards.sol", "SkyLocker.sol", "SkyFactory.sol"];
const sources = {};
for (const file of files) {
  sources[file] = { content: readFileSync(join(root, "contracts", file), "utf8") };
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    evmVersion: "cancun",
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};

function findImports(path) {
  const name = path.split("/").pop();
  if (!sources[name]) return { error: `not found: ${path}` };
  return { contents: sources[name].content };
}

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
if (output.errors?.length) {
  const fatal = output.errors.filter((e) => e.severity === "error");
  for (const err of output.errors) console.error(err.formattedMessage);
  if (fatal.length) process.exit(1);
}

const want = ["SkyToken", "SkyCurve", "SkyHook", "SkyPool", "SkyRewards", "SkyLocker", "SkyFactory"];
const compiled = {};
for (const name of want) {
  const file = `${name}.sol`;
  const art = output.contracts[file][name];
  const deployed = art.evm.deployedBytecode.object;
  const bytecode = art.evm.bytecode.object;
  const deployedBytes = deployed.length / 2;
  const initBytes = bytecode.length / 2;
  console.log(`${name}: init ${initBytes} bytes, runtime ${deployedBytes} bytes`);
  if (deployedBytes > 24576) {
    console.error(`${name} runtime exceeds 24KB`);
    process.exit(1);
  }
  compiled[name] = {
    abi: art.abi,
    bytecode: `0x${bytecode}`,
    deployedBytecode: `0x${deployed}`,
  };
}

const header = `/* Generated by scripts/compile-sky.mjs — do not edit by hand. */
/* solc ${solc.version()} | optimizer 200 | evm cancun */
import type { Abi } from "viem";

`;

const body = `export const compilerVersion = ${JSON.stringify(solc.version())};

export const tokenAbi = ${JSON.stringify(compiled.SkyToken.abi, null, 2)} as const satisfies Abi;
export const tokenBytecode = ${JSON.stringify(compiled.SkyToken.bytecode)} as const;
export const tokenDeployedBytecode = ${JSON.stringify(compiled.SkyToken.deployedBytecode)} as const;

export const curveAbi = ${JSON.stringify(compiled.SkyCurve.abi, null, 2)} as const satisfies Abi;
export const curveBytecode = ${JSON.stringify(compiled.SkyCurve.bytecode)} as const;
export const curveDeployedBytecode = ${JSON.stringify(compiled.SkyCurve.deployedBytecode)} as const;

export const hookAbi = ${JSON.stringify(compiled.SkyHook.abi, null, 2)} as const satisfies Abi;
export const hookBytecode = ${JSON.stringify(compiled.SkyHook.bytecode)} as const;
export const hookDeployedBytecode = ${JSON.stringify(compiled.SkyHook.deployedBytecode)} as const;

export const poolAbi = ${JSON.stringify(compiled.SkyPool.abi, null, 2)} as const satisfies Abi;
export const poolBytecode = ${JSON.stringify(compiled.SkyPool.bytecode)} as const;
export const poolDeployedBytecode = ${JSON.stringify(compiled.SkyPool.deployedBytecode)} as const;

export const rewardsAbi = ${JSON.stringify(compiled.SkyRewards.abi, null, 2)} as const satisfies Abi;

export const factoryAbi = ${JSON.stringify(compiled.SkyFactory.abi, null, 2)} as const satisfies Abi;
export const factoryBytecode = ${JSON.stringify(compiled.SkyFactory.bytecode)} as const;
export const factoryDeployedBytecode = ${JSON.stringify(compiled.SkyFactory.deployedBytecode)} as const;
`;

const outPath = join(root, "src/lib/chain/artifacts.ts");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, header + body);

mkdirSync(join(root, "public/contracts"), { recursive: true });
writeFileSync(join(root, "public/contracts/standard-input.json"), JSON.stringify(input));
for (const file of files) {
  writeFileSync(join(root, "public/contracts", file), sources[file].content);
}
console.log("wrote", outPath);
